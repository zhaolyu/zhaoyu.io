#!/usr/bin/env node
/**
 * Emits static/tokens.css — the custom-property layer, with no components and
 * no Tailwind, for consumers that are not this app.
 *
 * The dashboards in the other repos are vanilla HTML/CSS on Cloudflare Pages.
 * They cannot import a Svelte component, but they can link one stylesheet, so
 * this is the only part of the design system that actually travels. Extracted
 * from app.css rather than maintained by hand for the same reason
 * design-tokens.test.ts exists: two hand-kept copies of a token set diverge.
 *
 * Usage:  pnpm tokens   (runs automatically via prebuild)
 * Served at https://zhaoyu.io/tokens.css once the site deploys.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const appCss = readFileSync(join(root, 'src/app.css'), 'utf8');
const outPath = join(root, 'static/tokens.css');

/** Body of a top-level `selector { ... }` block, brace-matched. */
function block(selector) {
  const start = appCss.indexOf(`${selector} {`);
  if (start === -1) throw new Error(`app.css has no ${selector} block`);

  const open = appCss.indexOf('{', start);
  let depth = 0;
  for (let i = open; i < appCss.length; i++) {
    if (appCss[i] === '{') depth++;
    if (appCss[i] === '}') depth--;
    if (depth === 0) return appCss.slice(open + 1, i);
  }
  throw new Error(`${selector} block is unterminated`);
}

/** Custom-property declarations only — comments and other rules are dropped. */
function declarations(body) {
  return [...body.matchAll(/--([a-z0-9-]+):\s*([^;]+);/g)].map(([, name, value]) => ({
    name,
    value: value.trim(),
  }));
}

const rootTokens = declarations(block(':root'));
const darkTokens = declarations(block('.dark'));

/**
 * --font-sans/--font-mono live in Tailwind's `@theme` block, not `:root`, so a
 * consumer linking this file would get the type scale with no families to hang
 * it on. They are lifted in deliberately; loading the webfonts is the
 * consumer's job, and the fallbacks in the value cover it if they don't.
 */
const themeFonts = declarations(block('@theme')).filter((t) => t.name.startsWith('font-'));

if (rootTokens.length < 50) {
  console.error(`Only ${rootTokens.length} tokens found in :root — did app.css change shape?`);
  process.exit(1);
}

const render = (tokens) => tokens.map((t) => `  --${t.name}: ${t.value};`).join('\n');

const css = `/**
 * zhaoyu.io design tokens — GENERATED by scripts/build-tokens-css.mjs.
 * Do not edit: edit src/app.css and run \`pnpm tokens\`.
 *
 * Custom properties only. No resets, no component styles, no Tailwind.
 * Add \`class="dark"\` to <html> for the dark theme; omit it for light.
 * Fonts: values name Geist Sans / Geist Mono with system fallbacks — load the
 * webfonts yourself if you want them.
 */
:root {
${render(themeFonts)}
${render(rootTokens)}
}

.dark {
${render(darkTokens)}
}
`;

writeFileSync(outPath, css);
console.log(
  `tokens.css: ${themeFonts.length + rootTokens.length} tokens, ${darkTokens.length} dark overrides → static/tokens.css`,
);
