/**
 * The pure half of the `styles.css` + conventions part of `pnpm design-system`.
 *
 * Claude Design renders every design it produces with only `styles.css`'s
 * `@import` closure — the `@dsCard` previews are for humans in the picker, not
 * for the design agent's output. So the token vocabulary only reaches designs
 * if a `styles.css` at the bundle root declares it. This builds that file from
 * the already-generated `static/tokens.css` (the travelling token layer) plus
 * the web fonts, and resolves the conventions header against the same tokens
 * so the README never names a `var(--…)` that does not exist in a design.
 *
 * Kept free of filesystem access so design-system-styles.test.ts can run it
 * against the committed app.css / tokens.css / conventions.md and fail on
 * drift, without a build.
 */

/**
 * Web fonts shipped alongside `styles.css`. The site loads exactly these two
 * faces at weight 400 (bold is synthesized); matching that keeps the bundle at
 * ~45 KB of fonts and the rendered designs metrically identical to the site.
 * `source` is relative to the @fontsource package, `file` is the name under
 * `fonts/` in the bundle.
 */
export const FONT_FILES = [
  {
    family: 'Geist Sans',
    pkg: '@fontsource/geist-sans',
    source: 'files/geist-sans-latin-400-normal.woff2',
    file: 'geist-sans-latin-400-normal.woff2',
  },
  {
    family: 'Geist Mono',
    pkg: '@fontsource/geist-mono',
    source: 'files/geist-mono-latin-400-normal.woff2',
    file: 'geist-mono-latin-400-normal.woff2',
  },
];

const FALLBACK_FAMILY = 'Geist Sans Fallback';

/**
 * The metric-matched fallback face, lifted verbatim from app.css rather than
 * re-declared here: its size-adjust / ascent-override numbers were measured
 * against the real font files, and two hand-kept copies of measured values
 * diverge the same way two token sets do.
 * @param {string} appCss
 * @returns {string}
 */
export function fallbackFontFace(appCss) {
  const match = appCss.match(
    new RegExp(`@font-face\\s*\\{[^}]*font-family:\\s*'${FALLBACK_FAMILY}'[^}]*\\}`),
  );
  if (!match) throw new Error(`app.css has no @font-face for '${FALLBACK_FAMILY}'`);
  return match[0];
}

/**
 * @param {{ family: string, file: string }} font
 * @param {string} fontsDir
 */
function fontFace(font, fontsDir) {
  return `@font-face {
  font-family: '${font.family}';
  font-style: normal;
  font-weight: 400;
  font-display: swap;
  src: url('./${fontsDir}/${font.file}') format('woff2');
}`;
}

/**
 * Assemble `styles.css` for the bundle: fonts first (so `--font-sans` resolves
 * to a loaded face), then the token layer verbatim.
 * @param {{ appCss: string, tokensCss: string, fontsDir?: string }} input
 * @returns {string}
 */
export function buildStylesCss({ appCss, tokensCss, fontsDir = 'fonts' }) {
  if (!/:root\s*\{/.test(tokensCss) || !/\.dark\s*\{/.test(tokensCss)) {
    throw new Error('tokens.css is missing its :root or .dark block — run `pnpm tokens`');
  }

  const faces = [...FONT_FILES.map((f) => fontFace(f, fontsDir)), fallbackFontFace(appCss)];

  return `/**
 * zhaoyu.io design system — styles.css for Claude Design. GENERATED by
 * scripts/build-design-system.mjs; do not edit. Edit src/app.css, then
 * \`pnpm build && pnpm design-system\`.
 *
 * Rendered designs receive only this file's @import closure, so everything a
 * design may reference is declared here: the two web fonts, the metric-matched
 * fallback, and the full custom-property layer (:root light, .dark overrides).
 * Add class="dark" to the root element for the dark theme.
 */
${faces.join('\n\n')}

${tokensCss.trimEnd()}
`;
}

/**
 * Custom-property names declared in a generated tokens.css (`:root` and `.dark`).
 * @param {string} tokensCss
 * @returns {Set<string>}
 */
export function declaredTokens(tokensCss) {
  return new Set([...tokensCss.matchAll(/^\s*--([a-z0-9-]+):/gm)].map(([, name]) => name));
}

/**
 * Token references in a conventions document. Supports two shorthands so the
 * header stays readable without going unchecked:
 *   `--status-{success,warning,error}-text`  → expands the braces
 *   `--scrollbar-*`                           → a family prefix
 * @param {string} markdown
 * @returns {{ names: Set<string>, prefixes: Set<string> }}
 */
export function referencedTokens(markdown) {
  const names = new Set();
  const prefixes = new Set();

  for (const [, raw] of markdown.matchAll(/--([a-z0-9{},*-]+)/g)) {
    if (raw.endsWith('-*')) {
      prefixes.add(raw.slice(0, -2));
      continue;
    }
    for (const name of expandBraces(raw)) {
      // A trailing hyphen is prose ("--space- steps"), not a token.
      if (/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name)) names.add(name);
    }
  }
  return { names, prefixes };
}

/**
 * `a-{b,c}-{d,e}` → `a-b-d`, `a-b-e`, `a-c-d`, `a-c-e`. One level is all the
 * header needs; nested braces are not supported and would surface as an
 * unresolved name, which is the right failure.
 * @param {string} pattern
 * @returns {string[]}
 */
function expandBraces(pattern) {
  const m = pattern.match(/^(.*?)\{([^{}]*)\}(.*)$/);
  if (!m) return [pattern];
  const [, head, alts, tail] = m;
  return alts.split(',').flatMap((alt) => expandBraces(`${head}${alt}${tail}`));
}

/**
 * Every reference in the conventions document that no token satisfies.
 * Empty means the header is safe to ship in front of the design agent.
 * @param {string} markdown
 * @param {string} tokensCss
 * @returns {string[]}
 */
export function unresolvedConventionTokens(markdown, tokensCss) {
  const declared = declaredTokens(tokensCss);
  const { names, prefixes } = referencedTokens(markdown);
  const declaredList = [...declared];

  return [
    ...[...names].filter((name) => !declared.has(name)).map((name) => `--${name}`),
    ...[...prefixes]
      .filter((prefix) => !declaredList.some((name) => name.startsWith(`${prefix}-`)))
      .map((prefix) => `--${prefix}-*`),
  ].sort();
}

/**
 * Token families (first name segment) that tokens.css declares but the
 * conventions document never mentions. A new family in app.css must earn a
 * line in the header, for the same reason design-tokens.ts must register it.
 * @param {string} markdown
 * @param {string} tokensCss
 * @returns {string[]}
 */
export function undocumentedTokenFamilies(markdown, tokensCss) {
  const families = new Set([...declaredTokens(tokensCss)].map((name) => name.split('-')[0]));
  const { names, prefixes } = referencedTokens(markdown);
  const mentioned = new Set([...names, ...prefixes].map((name) => name.split('-')[0]));
  return [...families].filter((family) => !mentioned.has(family)).sort();
}
